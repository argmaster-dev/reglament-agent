import json
import subprocess
import sys
from pathlib import Path

import pytest

from reglament_agent.ops import provenance
from reglament_agent.ops.provenance import MANIFEST_NAME, source_inventory


def make_tree(root, *, reverse=False):
    files = {
        "src/agent/module.py": b"return_value = 1\n",
        "migrations/0001_initial.sql": b"SELECT 1;\n",
        "uv.lock": b"version = 1\n",
    }
    for name, content in sorted(files.items(), reverse=reverse):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    return root


def test_digest_tracks_file_paths_and_bytes_in_any_creation_order(tmp_path):
    first = make_tree(tmp_path / "first")
    second = make_tree(tmp_path / "second", reverse=True)
    bytecode = second / "src/agent/__pycache__/module.cpython-312.pyc"
    bytecode.parent.mkdir()
    bytecode.write_bytes(b"generated bytecode")
    (second / "src/agent/module.pyc").write_bytes(b"stray bytecode")

    expected = source_inventory(first).digest
    assert source_inventory(second).digest == expected
    target = second / "src/agent/module.py"
    target.write_bytes(b"return_value = 2\n")
    assert source_inventory(second).digest != expected
    target.write_bytes(b"return_value = 1\n")
    target.rename(target.with_name("renamed.py"))
    assert source_inventory(second).digest != expected


def test_cli_manifest_rejects_missing_or_changed_file(tmp_path):
    root = make_tree(tmp_path / "tree")
    script = Path(__file__).resolve().parents[2] / "scripts" / "source_digest.py"
    manifest = root / MANIFEST_NAME
    args = [sys.executable, str(script), "--root", str(root)]
    output = subprocess.check_output([*args, "--write-manifest", str(manifest)], text=True).strip()
    assert output == source_inventory(root).digest == json.loads(manifest.read_text())["source_digest"]
    assert subprocess.check_output(args, text=True).strip() == output

    path = root / "src/agent/additional.py"
    path.write_bytes(b"untracked")
    with pytest.raises(ValueError, match="inventory"):
        source_inventory(root)
    path.unlink()

    path = root / "src/agent/module.py"
    content = path.read_bytes()
    path.write_bytes(content + b" ")
    with pytest.raises(ValueError, match="digest"):
        source_inventory(root)
    path.unlink()
    with pytest.raises(ValueError, match="inventory"):
        source_inventory(root)


def test_digest_requires_git_tracked_inputs_even_when_other_sources_remain(tmp_path):
    root = make_tree(tmp_path / "tree")
    other_source = root / "src/agent/other.py"
    other_source.write_bytes(b"hello")
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    subprocess.run(["git", "-C", str(root), "add", "src", "migrations", "uv.lock"], check=True)
    (root / "src/agent/module.py").unlink()
    with pytest.raises(ValueError, match="tracked"):
        source_inventory(root)
    (root / "uv.lock").unlink()
    with pytest.raises(FileNotFoundError, match="uv.lock"):
        source_inventory(root)



def test_build_reports_verified_release_and_caches_source_digest(tmp_path, monkeypatch):
    root = make_tree(tmp_path / "tree")
    source = source_inventory(root)
    (root / MANIFEST_NAME).write_text(json.dumps(source.manifest()))
    monkeypatch.setattr(provenance, "PROJECT_ROOT", root)
    monkeypatch.setenv("BUILD_SHA", "a" * 40)
    monkeypatch.setenv("BUILD_TAG", "v1.0.0")
    monkeypatch.setenv("BUILD_TIME", "2026-11-27T00:00:00Z")
    monkeypatch.setenv("BUILD_DIRTY", "false")
    provenance.build_identity.cache_clear()
    provenance._runtime_source.cache_clear()
    try:
        build, status = provenance.build_details()
        assert status == "verified"
        assert build == {
            "sha": "a" * 40,
            "tag": "v1.0.0",
            "time": "2026-11-27T00:00:00Z",
            "dirty": False,
            "source_digest": source.digest,
        }
        assert provenance.release_info() == {"sha7": "a" * 7, "tag": "v1.0.0", "dirty": False}
        (root / MANIFEST_NAME).unlink()
        assert provenance.build_details() == (build, status)
        provenance._runtime_source.cache_clear()
        unverified, status = provenance.build_details()
        assert status == "invalid" and unverified["source_digest"] is None
    finally:
        provenance._runtime_source.cache_clear()
        provenance.build_identity.cache_clear()


def test_image_digests_expose_only_known_services_and_digest_fields(monkeypatch):
    image_id = "sha256:" + "c" * 64
    manifest_digest = "sha256:" + "d" * 64
    monkeypatch.setenv("REGULATIONS_IMAGE_DIGESTS", json.dumps({
        "app": {"image_id": image_id, "secret": "not evidence"},
        "postgres": {"image_id": image_id, "manifest_digest": manifest_digest},
        "gateway": {"image_id": "a mutable tag"},
        "unexpected": {"image_id": image_id},
    }))
    assert provenance.deployment_image_digests() == {
        "app": {"image_id": image_id},
        "postgres": {"image_id": image_id, "manifest_digest": manifest_digest},
    }
    monkeypatch.setenv("REGULATIONS_IMAGE_DIGESTS", "")
    assert provenance.deployment_image_digests() == {}
