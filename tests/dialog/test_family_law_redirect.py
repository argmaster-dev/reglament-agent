"""Family-law entitlements, payroll workflows and unrelated meanings of family terms."""

import pytest

from reglament_agent.dialog.guards import redirect_for


@pytest.mark.parametrize("question", [
    "От чего зависит сумма алиментов при нерегулярном доходе?",
    "Кто вправе требовать алиментные выплаты?",
    "В каких случаях устанавливают отцовство через суд?",
    "Можно ли подать на алименты после расторжения брака?",
    "Куда передать заявление о взыскании алиментов, в суд или приставу?",
    "Можно ли оспорить брачный договор после развода?",
    "Кому достанется совместно нажитое имущество при расторжении брака?",
    "Есть ли основания для лишения родительских прав?",
])
def test_family_law_entitlement_or_proceeding_has_a_legal_recipient(question):
    assert redirect_for(question) == "legal"


@pytest.mark.parametrize("question", [
    "В каком поле расчетной ведомости указывать размер алиментов?",
    "Как бухгалтеру зарегистрировать исполнительный лист на алименты в зарплатной системе?",
    "Кому в отделе кадров передать сведения об установленном отцовстве?",
    "Кому в бухгалтерии передать документ о выплате алиментов до отправки приставу?",
    "Где во внутренней инструкции описано оформление удержания алиментов?",
    "Можно ли занести брачный договор в карточку сотрудника?",
    "Кто оформляет акт о браке поставленной продукции?",
    "Как убрать разводы после покраски детали?",
    "Что означает алиментарное происхождение заболевания?",
    "Сколько стоит курс по осознанному материнству?",
    "Сколько стоит распечатать брачный договор?",
    "Какие права наследует дочерняя роль от родительской?",
    "Пропала папка с рабочим названием «Алименты». Где она?",
    "На какой платформе показывали сериал «Алименты»?",
])
def test_internal_work_or_an_ambiguous_family_term_keeps_normal_routing(question):
    assert redirect_for(question) is None
